// Compares the runtime's `obsidian` module with Obsidian's published API declarations
// (`obsidian.d.ts` from the `obsidian` npm package, version pinned in package.json): which
// exported classes, functions and constants exist, and which declared methods each class
// has. Properties are not checked, since they exist only on constructed objects.
//
// Usage: node compatibility/api-coverage.js [--markdown]
'use strict';

const fileSystem = require('node:fs');
const path = require('node:path');
const typescript = require('typescript');
const { startRuntime } = require('../support/runtime-harness');

const declarationsPath = require.resolve('obsidian/obsidian.d.ts');
const apiVersion = require('obsidian/package.json').version;

function declaredApi() {
    const sourceFile = typescript.createSourceFile(declarationsPath, fileSystem.readFileSync(declarationsPath, 'utf8'), typescript.ScriptTarget.Latest, true);
    const classes = new Map();
    const values = [];
    const hasExport = (node) => (typescript.getCombinedModifierFlags(node) & typescript.ModifierFlags.Export) !== 0;
    for (const statement of sourceFile.statements) {
        if (typescript.isClassDeclaration(statement) && statement.name && hasExport(statement)) {
            const methods = new Set();
            const staticMethods = new Set();
            for (const member of statement.members) {
                if (!typescript.isMethodDeclaration(member) || !member.name || !typescript.isIdentifier(member.name)) continue;
                const modifierFlags = typescript.getCombinedModifierFlags(member);
                // An abstract method is the subclass's to implement (Graphite's editor implements
                // `Editor`'s), so the declaring class is not expected to have it.
                if ((modifierFlags & typescript.ModifierFlags.Abstract) !== 0) continue;
                const isStatic = (modifierFlags & typescript.ModifierFlags.Static) !== 0;
                (isStatic ? staticMethods : methods).add(member.name.text);
            }
            const heritage = (statement.heritageClauses || []).find((clause) => clause.token === typescript.SyntaxKind.ExtendsKeyword);
            const parentName = heritage ? heritage.types[0].expression.getText(sourceFile) : null;
            classes.set(statement.name.text, { methods, staticMethods, parentName });
        } else if (typescript.isFunctionDeclaration(statement) && statement.name && hasExport(statement)) {
            values.push(statement.name.text);
        } else if (typescript.isVariableStatement(statement) && hasExport(statement)) {
            for (const declaration of statement.declarationList.declarations) values.push(declaration.name.getText(sourceFile));
        } else if (typescript.isEnumDeclaration(statement) && hasExport(statement)) {
            values.push(statement.name.text);
        }
    }
    return { classes, values: Array.from(new Set(values)) };
}

async function measureCoverage() {
    const harness = await startRuntime({ files: {} });
    const runtimeModule = harness.obsidian;
    const { classes, values } = declaredApi();
    const missingValues = values.filter((name) => !(name in runtimeModule));
    const missingClasses = [];
    const classesWithMissingMethods = [];
    let declaredMethodCount = 0;
    let presentMethodCount = 0;
    for (const [className, declaration] of classes) {
        const runtimeClass = runtimeModule[className];
        declaredMethodCount += declaration.methods.size + declaration.staticMethods.size;
        if (typeof runtimeClass !== 'function') { missingClasses.push(className); continue; }
        const missingMethods = [];
        for (const methodName of declaration.methods) {
            if (typeof runtimeClass.prototype[methodName] === 'function') presentMethodCount += 1; else missingMethods.push(methodName);
        }
        for (const methodName of declaration.staticMethods) {
            if (typeof runtimeClass[methodName] === 'function') presentMethodCount += 1; else missingMethods.push('static ' + methodName);
        }
        if (missingMethods.length > 0) classesWithMissingMethods.push({ className, missingMethods });
    }
    harness.close();
    return {
        apiVersion,
        declaredClassCount: classes.size,
        presentClassCount: classes.size - missingClasses.length,
        declaredValueCount: values.length,
        presentValueCount: values.length - missingValues.length,
        declaredMethodCount,
        presentMethodCount,
        missingClasses: missingClasses.sort(),
        missingValues: missingValues.sort(),
        classesWithMissingMethods,
    };
}

function markdownReport(coverage) {
    const lines = [
        '# Obsidian API coverage of the plugin runtime',
        '',
        'Generated by `npm run api-coverage -- --markdown` in `Tests/CommunityPluginRuntimeTests`, against `obsidian.d.ts` ' + coverage.apiVersion + '.',
        'Presence is not behavior: a method that exists may still report itself as unsupported when called (see `Docs/Community-plugins.md`).',
        '',
        '| Declared in obsidian.d.ts | Present in the runtime |',
        '| --- | --- |',
        '| ' + coverage.declaredClassCount + ' exported classes | ' + coverage.presentClassCount + ' |',
        '| ' + coverage.declaredMethodCount + ' class methods | ' + coverage.presentMethodCount + ' |',
        '| ' + coverage.declaredValueCount + ' exported functions and constants | ' + coverage.presentValueCount + ' |',
        '',
        '## Missing classes',
        '',
        coverage.missingClasses.length ? coverage.missingClasses.map((name) => '`' + name + '`').join(', ') : 'None.',
        '',
        '## Missing functions and constants',
        '',
        coverage.missingValues.length ? coverage.missingValues.map((name) => '`' + name + '`').join(', ') : 'None.',
        '',
        '## Classes with missing methods',
        '',
        '| Class | Missing methods |',
        '| --- | --- |',
        ...coverage.classesWithMissingMethods.map((entry) => '| `' + entry.className + '` | ' + entry.missingMethods.map((name) => '`' + name + '`').join(', ') + ' |'),
        '',
    ];
    return lines.join('\n');
}

measureCoverage().then((coverage) => {
    if (process.argv.includes('--markdown')) process.stdout.write(markdownReport(coverage));
    else console.log(JSON.stringify(coverage, null, 2));
}).catch((error) => {
    console.error(error);
    process.exit(1);
});

module.exports = { declaredApi };
